# Variables
name = "Alice"
age = 20
marks = 95.5

# Using format()
print("Using format():")
print("Name: {}, Age: {}, Marks: {}".format(name, age, marks))

# Using f-strings
print("\nUsing f-strings:")
print(f"Name: {name}, Age: {age}, Marks: {marks}")

# Using % operator
print("\nUsing % operator:")
print("Name: %s, Age: %d, Marks: %.1f" % (name, age, marks))