# Creating a list
numbers = [30, 10, 50, 20, 40]

print("Original List:", numbers)

# Append an element
numbers.append(60)
print("After append(60):", numbers)

# Insert an element at a specific position
numbers.insert(2, 25)
print("After insert(2, 25):", numbers)

# Remove an element
numbers.remove(50)
print("After remove(50):", numbers)

# Sort the list
numbers.sort()
print("After sort():", numbers)

# Reverse the list
numbers.reverse()
print("After reverse():", numbers)