# String creation
str1 = "Hello"
str2 = "Python"

print("String 1:", str1)
print("String 2:", str2)

# Concatenation
result = str1 + " " + str2
print("Concatenation:", result)

# Repetition
print("Repetition:", str1 * 3)

# Slicing
print("First 3 characters:", str2[:3])
print("Last 3 characters:", str2[-3:])
print("Substring (1 to 4):", str2[1:5])
